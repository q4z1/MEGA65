#!/bin/sh
# Builds Wedge Turbo. The tools make what the game loads (build/gen, the
# files of the disk in build/disk): tools/mkdata.py the race's tables
# (from tools/gamedata.py), tools/mksprites.py the pictures,
# tools/mkcourses.py the courses (TRACKnn), tools/mkmusic.py and
# tools/mksounds.py the music (MUSIC) and the race's sounds (SOUNDS),
# tools/mkpages.py the screens around the race. Then
# everything is compiled into build/wedge-turbo.prg, which goes onto
# build/wedge-turbo.d81 together with the data files. The version is in the
# file VERSION.
# Called by .vscode/run-current.sh with the compiler in $MEGA65_CC.

set -e
cd "$(dirname "$0")"
CC=${MEGA65_CC:-../toolchain/llvm-mos/bin/mos-mega65-clang}
# the Python modules the tools use (Pillow), for the python3 at hand
PYTHONPATH="$(../toolchain/tools/python-modules.sh)${PYTHONPATH:+:$PYTHONPATH}"
export PYTHONPATH
VERSION=$(cat VERSION)

# build/gen and build/disk are made anew each time
rm -rf build/gen build/disk
mkdir -p build/gen build/disk
python3 tools/mkdata.py build/gen
python3 tools/mksounds.py build/gen
python3 tools/mksprites.py build/gen
python3 tools/mkpages.py build/gen
python3 tools/mkmusic.py build/gen
python3 tools/mkcourses.py build/gen
printf '// Generated by build.sh from VERSION - do not edit\n#define VERSION "%s"\n' "$VERSION" \
    > build/gen/version.h
# The structures' offsets and the constants for the assembly, from the C
# headers on the host
${HOST_CC:-cc} -Wall -Isrc -Ibuild/gen -o build/offsets tools/offsets.c
build/offsets > build/gen/offsets.inc

# src/ref/ holds the C references of what runs in assembly: not built here
# (tests/)
#
# The files that collect and run DMA jobs are compiled on their own, without
# link-time optimization: with it, llvm-mos got calls into dma.c wrong where
# they were inlined (pages came out garbled, depending on the rest of the
# program).
NO_LTO="dma banks pages"
mkdir -p build/obj
set --
for f in src/*.c; do
    n=$(basename "$f" .c)
    case " $NO_LTO " in
        *" $n "*)
            # shellcheck disable=SC2086
            "$CC" -Os -g -Wall $WEDGE_CFLAGS -Isrc -Ibuild/gen -DWEDGE_MENU_OVERLAY -fno-lto -c -o "build/obj/$n.o" "$f"
            set -- "$@" "build/obj/$n.o" ;;
        *) set -- "$@" "$f" ;;
    esac
done
# shellcheck disable=SC2086
"$CC" -Os -g -Wall $WEDGE_CFLAGS -Isrc -Ibuild/gen -o build/wedge-turbo.prg \
    -DWEDGE_MENU_OVERLAY -T link.ld -Wl,--no-check-sections -Wl,-Map=build/wedge-turbo.map "$@" src/*.s build/gen/*.c
# the pages' code, an overlay (link.ld): on the disk as MENU; the code
# under $1000: LOWCODE; the code run at the start: BOOT
OBJCOPY=${MEGA65_OBJCOPY:-../toolchain/llvm-mos/bin/llvm-objcopy}
"$OBJCOPY" -O binary --only-section=.menu build/wedge-turbo.prg.elf build/gen/menu.bin
"$OBJCOPY" -O binary --only-section=.lowcode build/wedge-turbo.prg.elf build/gen/lowcode.bin
"$OBJCOPY" -O binary --only-section=.bootcode build/wedge-turbo.prg.elf build/gen/boot.bin

# The data files, each behind two bytes of (unused) load address
set --
for f in build/gen/menu.bin build/gen/lowcode.bin build/gen/boot.bin build/gen/texts.bin build/gen/sounds.bin build/gen/music.bin build/gen/track*.bin build/gen/spr*.bin build/gen/back*.bin build/gen/panel.bin build/gen/lapbar.bin build/gen/carhi.bin build/gen/pages/*.bin; do
    name=$(basename "$f" .bin | tr a-z A-Z)
    { printf '\000\000'; cat "$f"; } > "build/disk/$name"
    set -- "$@" "build/disk/$name=$name"
done
../toolchain/tools/bin/mkd81.py build/wedge-turbo.d81 "WEDGE TURBO $VERSION" \
    "build/wedge-turbo.prg=WEDGE TURBO" "$@"
