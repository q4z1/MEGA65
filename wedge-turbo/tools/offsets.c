#define P(f) printf("P_%-14s = $%02zX\n", #f, offsetof(Player, f))
#define O(f) printf("O_%-14s = $%02zX\n", #f, offsetof(Opponent, f))
#define R(f) printf("R_%-14s = $%03zX\n", #f, offsetof(Race, f))

int main(void) {
    printf("; Generated by tools/offsets.c - do not edit\n");
    printf("PLAYER_SIZE      = $%02zX\nOPPONENT_SIZE    = $%02zX\nOPPONENTS        = %d\n",
           sizeof(Player), sizeof(Opponent), OPPONENTS);
    P(x); P(pos); P(speed); P(steer); P(curve); P(u16); P(in_pits); P(slope);
    P(x_pic); P(pos_pic); P(x_pic2); P(pos_pic2); P(in_pits_pic); P(pos_shown); P(x_shown);
    P(in_pits_shown); P(stopped); P(cam_pos); P(cam_x); P(x_view); P(pos_view); P(slope_view);
    P(u16_view); P(speed_view); P(steer_view); P(curve_view); P(automatic); P(push_x);
    P(push_steer); P(fuel); P(place); P(colours); P(accelerating); P(gear); P(rpm);
    P(pit_request); P(pit_lane); P(u96); P(flicker); P(flicker_r); P(joy_last); P(joy_new);
    P(joy); P(fire_accel); P(timer); P(pit_timer);
    O(pos); O(x); O(speed); O(target); O(dx);
    R(p); R(opp); R(segments); R(opponents); R(opp_length); R(seg_bias); R(finish);
    R(opp_bonus); R(clock); R(two_players); R(difficulty); R(control2); R(demo); R(frames);
    R(finished); R(next_finisher); R(finish_frames); R(over); R(over_timer); R(paused);
    R(random); R(sound_p1); R(sound_p2); R(scrape); R(hit); R(crash); R(control);
    R(opp_pic); R(opp_pic_x); R(buffer); R(course); R(race_no); R(laps);
    printf("RACE_SIZE        = $%03zX\n", sizeof(Race));
    printf("TRACK_SEGMENTS   = $%02zX\n", offsetof(Track, seg));

    // render.s
    printf("RL_x             = %zu\nRL_scale         = %zu\nRL_depth         = %zu\nROADLINE_SIZE    = %zu\n",
           offsetof(RoadLine, x), offsetof(RoadLine, scale), offsetof(RoadLine, depth), sizeof(RoadLine));
    printf("COL_GRASS        = %d\nCOL_SET_B        = %d\nFB_W             = %d\n", COL_GRASS, COL_SET_B, FB_W);
    printf("DMA_LIST         = $%04lX\nDMA_LIST_END     = $%04lX\n", (unsigned long)(uintptr_t)DMA_LIST,
           (unsigned long)(uintptr_t)DMA_LIST + DMA_LIST_SIZE);
    printf("PICTURE          = $%05lX\nATTIC            = $%07lX\n", PICTURE, ATTIC);
    printf("MUSIC_ATTIC      = $%07lX\n", MUSIC_ATTIC);
    printf("PAGE_SCREEN      = $%05lX\n", PAGE_SCREEN);
    printf("ROAD_RUNS_MAX    = %d\nROAD_EDGE_BASE   = $%04X\nROAD_MIX         = %d\n", ROAD_RUNS_MAX,
           (uint16_t)ROAD_EDGE_BASE, ROAD_MIX);
    printf("ROADIDX          = $%05lX\nROADPIX          = $%07lX\nROADPIX_B        = $%05lX\n", ROADIDX, ROADPIX,
           ROADPIX_B);
    printf("SP_bank          = %zu\nSP_image         = %zu\nSP_x             = %zu\nSP_y             = %zu\n"
           "SP_clip          = %zu\nSPRITE_SIZE      = %zu\nSPR_CLEAR        = $%02X\n",
           offsetof(Sprite, bank), offsetof(Sprite, image), offsetof(Sprite, x), offsetof(Sprite, y),
           offsetof(Sprite, clip), sizeof(Sprite), SPR_CLEAR);
    return 0;
}
