// Wedge Turbo: the offsets of the C structures and the constants the
// assembly needs, as assembler symbols (race.s, render.s). Built and run on
// the host by build.sh; the structures are packed or of 16-bit fields only,
// so the host's offsets are the MEGA65's.
//
//   offsets > build/gen/offsets.inc

#include <stddef.h>
#include <stdint.h>
#include <stdio.h>

#include "dma.h"
#include "fb.h"
#include "mem.h"
#include "race.h"
#include "render.h"
#include "road.h"
#include "road_rows.h"
#include "roadpat.h"
