#!/usr/bin/env python3
"""Converts the game's data (from extract.py) into what Lotus Run uses.

    mkdata.py ORIGDIR GENDIR

Writes into GENDIR:
    tables.c/.h   the projection tables from file $59
    roadpat.c/.h  the road line patterns of file $59 as a model: per
                  variant its runs of kerb, road and lane colour and where
                  their edges lie for a given road width
    progdata.c    tables from the game program: the car's physics, the
                  scenery's widths, laps and opponents per course, the grid
    trackNN.bin   the courses, as the game keeps them in memory: 16 bytes
                  per segment (the 12 of the file, 4 zero), the first 8
                  segments repeated at the end; header in tracks.h's layout
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import packers  # noqa: E402

# file $59 unpacked: road line pictures, then the tables
F59_PTRS, F59_RECIP, F59_BASE, F59_SCALE = 0xB99C, 0xC19C, 0xD19C, 0xD29C
F59_OBJECT_SIZE, F59_CAR_SIZE = 0xD39C, 0xD49C

TRACKS = 32


def c_array(name, ctype, values, per_line=12):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append('    ' + ', '.join(str(v) for v in values[i:i + per_line]) + ',')
    return f'const {ctype} {name}[{len(values)}] = {{\n' + '\n'.join(lines) + '\n};\n'


def tables(orig, gen):
    d = packers.unpack_bytes(open(os.path.join(orig, '59.bin'), 'rb').read())
    scale = list(struct.unpack_from('>128H', d, F59_SCALE))
    base = list(struct.unpack_from('>128H', d, F59_BASE))
    object_size = list(struct.unpack_from('>128h', d, F59_OBJECT_SIZE))
    car_size = list(struct.unpack_from('>128h', d, F59_CAR_SIZE))
    # the reciprocal table follows a formula that road.c computes instead
    recip = struct.unpack_from('>1024i', d, F59_RECIP)
    for i, v in enumerate(recip):
        if i & 15 > 1 and v != (((i & ~15) << 16) // (i & 15)) & ~0xFFF:
            sys.exit(f'file $59: reciprocal table entry {i} is not as road.c computes it')
    with open(os.path.join(gen, 'tables.h'), 'w') as f:
        f.write('// Generated by tools/mkdata.py from file $59 - do not edit\n'
                '#pragma once\n#include <stdint.h>\n'
                '// per depth step: perspective scale and road line\n'
                'extern const uint16_t tab_scale[128];\n'
                'extern const uint8_t tab_base[128];\n'
                '// per depth step: which of the 17 sizes of a scenery object and of a\n'
                '// car (0 the largest; -1 none)\n'
                'extern const int8_t tab_object_size[128];\n'
                'extern const int8_t tab_car_size[128];\n')
    with open(os.path.join(gen, 'tables.c'), 'w') as f:
        f.write('// Generated by tools/mkdata.py - do not edit\n#include "tables.h"\n\n')
        f.write(c_array('tab_scale', 'uint16_t', scale))
        f.write(c_array('tab_base', 'uint8_t', base, 24))
        f.write(c_array('tab_object_size', 'int8_t', object_size, 24))
        f.write(c_array('tab_car_size', 'int8_t', car_size, 24))


def road_patterns(d):
    """For width w (0-255) and variant v, the runs from the left kerb to the
    right one: (colour 1 kerb / 2 road / 3 lane, start, length), start
    relative to the picture's reference point 357 + w (see render.c)."""
    ptrs = struct.unpack_from('>512i', d, F59_PTRS)
    plane2 = 0x5C6E  # second bitplane

    def runs(p, w):
        out, cur, start = [], None, 0
        for x in range(357 + w + 420):
            v = ((d[p + x // 8] >> (7 - x % 8)) & 1) | (((d[p + plane2 + x // 8] >> (7 - x % 8)) & 1) << 1)
            if v != cur:
                if cur is not None:
                    out.append((cur, start - 357 - w, x - start))
                cur, start = v, x
        road, kerbs = [], 0
        for r in out[next(i for i, r in enumerate(out) if r[0] == 1):]:
            road.append(r)
            kerbs += r[0] == 1
            if kerbs == 2:
                return road
        raise ValueError(f'width {w}: no road')

    pat = {}
    for v in (0, 1):
        for w in range(256):
            if ptrs[2 * w + v] >= 0:
                pat[(w, v)] = runs(ptrs[2 * w + v], w)
    # missing ones (the game only has variant 1 for the widths of a flat
    # road, and nothing below width 8): scaled from the nearest one there is
    for v in (0, 1):
        have = sorted(w for (w, vv) in pat if vv == v)
        for w in range(256):
            if (w, v) in pat:
                continue
            src = min(have, key=lambda h: (abs(h - w), h))
            f = max(w, 1) / src
            edges = [r[1] for r in pat[(src, v)]] + [pat[(src, v)][-1][1] + pat[(src, v)][-1][2]]
            # scale around the road's centre, keep every run at least 1 pixel
            mid = (edges[0] + edges[-1]) / 2
            new = [round(mid * max(w, 1) / src + (e - mid) * f) for e in edges]
            for i in range(1, len(new)):
                new[i] = max(new[i], new[i - 1] + 1)
            pat[(w, v)] = [(r[0], new[i], new[i + 1] - new[i]) for i, r in enumerate(pat[(src, v)])]
    return pat


# The edges of the patterns drawn out at the start (road_rows.c): for each
# of 512 widths (scale >> 3) and both variants, edge k in 1/64 pixel is
# c * w2 + c / 2 + ROAD_EDGE_BASE, 4 phases a quarter pixel apart
ROAD_EDGE_BASE = -1312  # -20.5 pixels


def road_extent(c, w2):
    """The pixels a pattern of width w2 with edge coefficients c covers in
    all its phases: (first, count), as road_rows.c computes them."""
    first = c[0] * w2 + (c[0] >> 1) + ROAD_EDGE_BASE
    last = c[-1] * w2 + (c[-1] >> 1) + ROAD_EDGE_BASE
    start = (first - 48) >> 6
    return start, ((last + 63) >> 6) - start


def roadpat(orig, gen):
    """The game's road line patterns are drawn from a road of 2 x the
    width w: every edge lies at c / 32 * w (rounded down) from the road's
    middle. Finds c for every edge (from the widths with all of them) and
    checks that the patterns follow it."""
    d = packers.unpack_bytes(open(os.path.join(orig, '59.bin'), 'rb').read())
    ptrs = struct.unpack_from('>512i', d, F59_PTRS)
    pat = road_patterns(d)
    edges, colours = [], []
    for v in (0, 1):
        runs = max(len(pat[(w, v)]) for w in range(256))
        ws = [w for w in range(256) if ptrs[2 * w + v] >= 0 and len(pat[(w, v)]) == runs]
        cols = [r[0] for r in pat[(ws[0], v)]]
        c = []
        for k in range(runs + 1):
            e = [pat[(w, v)][k][1] if k < runs else pat[(w, v)][-1][1] + pat[(w, v)][-1][2] for w in ws]
            mw, me = sum(ws) / len(ws), sum(e) / len(e)
            a = sum((w - mw) * (y - me) for w, y in zip(ws, e)) / sum((w - mw) ** 2 for w in ws)
            c.append(round(a * 32))
            worst = max(abs(y - (c[-1] * w / 32 + ROAD_EDGE_BASE / 64)) for w, y in zip(ws, e))
            if worst > 2:
                raise ValueError(f'road pattern variant {v}, edge {k}: off by {worst:.2f} pixels')
        if any(pat[(w, v)][k][0] != cols[k] for w in ws for k in range(runs)) or c != sorted(c):
            raise ValueError(f'road pattern variant {v}: runs do not match')
        edges.append(c)
        colours.append(cols)
    most = max(len(c) for c in colours)
    # the four phases of a width and variant together, never across 64K
    # (a DMA job keeps to its bank): the way road_pixels.c lays them out
    pixels = 0
    for w2 in range(512):
        for c in edges:
            size = 4 * road_extent(c, w2)[1]
            if pixels >> 16 != (pixels + size - 1) >> 16:
                pixels = (pixels | 0xFFFF) + 1
            pixels += size
    longest = max(road_extent(c, w2)[1] for c in edges for w2 in range(512))
    with open(os.path.join(gen, 'roadpat.h'), 'w') as f:
        f.write('// Generated by tools/mkdata.py from file $59 - do not edit\n'
                '#pragma once\n#include <stdint.h>\n'
                '// The road line patterns: variant v (a line\'s x & 1) has road_runs[v]\n'
                '// runs, from the left kerb\'s outer edge to the right one\'s, run k in\n'
                '// colour road_colour[v][k] (1 kerb, 2 road, 3 lane) from edge k to\n'
                '// edge k + 1. For a road of width s (a line\'s scale / 16) edge k lies\n'
                '// road_edge[v][k] * s / 32 + ROAD_EDGE_BASE / 64 pixels from the line\'s\n'
                '// reference point (road_rows.c).\n'
                f'#define ROAD_RUNS_MAX {most}\n'
                f'#define ROAD_EDGE_BASE ({ROAD_EDGE_BASE})\n'
                '// all patterns drawn out (road_pixels.c): bytes per stripe set; the\n'
                '// longest\n'
                f'#define ROAD_PIXELS {pixels}ul\n'
                f'#define ROAD_LEN_MAX {longest}\n'
                'extern const uint8_t road_runs[2];\n'
                'extern const int8_t road_edge[2][ROAD_RUNS_MAX + 1];\n'
                'extern const uint8_t road_colour[2][ROAD_RUNS_MAX];\n')
    with open(os.path.join(gen, 'roadpat.c'), 'w') as f:
        f.write('// Generated by tools/mkdata.py - do not edit\n#include "roadpat.h"\n\n')
        f.write('const uint8_t road_runs[2] = {%s};\n' % ', '.join(str(len(c)) for c in colours))
        f.write('const int8_t road_edge[2][ROAD_RUNS_MAX + 1] = {\n%s};\n' %
                ''.join('    {%s},\n' % ', '.join(map(str, c)) for c in edges))
        f.write('const uint8_t road_colour[2][ROAD_RUNS_MAX] = {\n%s};\n' %
                ''.join('    {%s},\n' % ', '.join(map(str, c)) for c in colours))


# Where the program's code hunk runs (extract.py); tables by address
CODE_BASE = 0xC18880
PROGRAM_TABLES = [
    # name, C type, address, count, struct format of one element
    ('tab_gear_ratio', 'uint16_t', 0xC23742, 5, 'H'),
    ('tab_torque', 'int16_t', 0xC236AA, 76, 'h'),
    ('tab_torque_acc', 'int16_t', 0xC23612, 76, 'h'),
    ('tab_grip', 'int8_t', 0xC2376E, 64, 'b'),
    ('tab_object_width', 'uint8_t', 0xC235E4, 44, 'B'),
    ('tab_object_colours', 'uint16_t', 0xC23484, 44 * 4, 'H'),
    ('tab_laps', 'uint8_t', 0xC237B4, 32, 'B'),
    ('tab_opp_bonus', 'uint8_t', 0xC2374C, 32, 'B'),
    ('tab_course_base', 'uint16_t', 0xC23FEA, 4, 'H'),
    ('tab_grid_x', 'int16_t', 0xC21CBA, 20, 'h'),
    ('tab_grid_pos', 'uint32_t', 0xC21CE2, 20, 'I'),
    # the pictures (sprites.c)
    ('tab_car_image', 'uint8_t', 0xC21C00, 17 * 9, 'B'),
    ('tab_gate', 'int8_t', 0xC20B1E, 28, 'h'),
    ('tab_brake', 'int8_t', 0xC20E30, 45, 'h'),
    ('tab_countdown', 'int8_t', 0xC237F0, 12, 'h'),
]


# The display list of the first picture (hunk 1, at $B168 when the game
# runs): the colours of the race view, set at its first line
LIST_BASE = 0xB168
VIEW_COLOURS = 0xB280  # MOVE COLOR01 ... COLOR07


PANEL_COLOURS = 0xB29C  # MOVE COLOR17 ... COLOR31: the panel's sprites


def panel_colours(orig):
    """Colours 17-19 and 25-27 (the panel's two sprite colour sets)"""
    import amiga
    hunk = bytes(amiga.parse_hunks(open(os.path.join(orig, 'main.bin'), 'rb').read())[1]['data'])
    moves = struct.unpack_from('>24H', hunk, PANEL_COLOURS - LIST_BASE)
    regs = list(moves[0::2])
    if regs != [0x1A2, 0x1A4, 0x1A6, 0x1AA, 0x1AC, 0x1AE, 0x1B2, 0x1B4, 0x1B6, 0x1BA, 0x1BC, 0x1BE]:
        sys.exit('main.bin: the panel colours are not where expected')
    return list(moves[1:6:2]) + list(moves[13:18:2])


def view_colours(orig):
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import amiga
    hunk = bytes(amiga.parse_hunks(open(os.path.join(orig, 'main.bin'), 'rb').read())[1]['data'])
    moves = struct.unpack_from('>14H', hunk, VIEW_COLOURS - LIST_BASE)
    if list(moves[0::2]) != list(range(0x182, 0x190, 2)):
        sys.exit('main.bin: the race view colours are not where expected')
    return list(moves[1::2])


def program_tables(orig, gen):
    code = open(os.path.join(orig, 'code.bin'), 'rb').read()
    h = ['// Generated by tools/mkdata.py from the game program - do not edit',
         '#pragma once', '#include <stdint.h>']
    c = ['// Generated by tools/mkdata.py - do not edit', '#include "progdata.h"', '']
    for name, ctype, addr, count, fmt in PROGRAM_TABLES:
        values = struct.unpack_from('>%d%s' % (count, fmt), code, addr - CODE_BASE)
        h.append(f'extern const {ctype} {name}[{count}];  // ${addr:06X}')
        c.append(c_array(name, ctype, list(values)))
    h.append('extern const uint16_t tab_view_colours[7];  // colours 1-7 of the race view')
    c.append(c_array('tab_view_colours', 'uint16_t', view_colours(orig)))
    h.append('extern const uint16_t tab_panel_colours[6];  // colours 17-19 and 25-27: the panel')
    c.append(c_array('tab_panel_colours', 'uint16_t', panel_colours(orig)))
    with open(os.path.join(gen, 'progdata.h'), 'w') as f:
        f.write('\n'.join(h) + '\n')
    with open(os.path.join(gen, 'progdata.c'), 'w') as f:
        f.write('\n'.join(c))


def tracks(orig, gen):
    largest = 0
    for t in range(TRACKS):
        d = open(os.path.join(orig, f'{t:02X}.bin'), 'rb').read()
        n = struct.unpack_from('>H', d, 0)[0]
        header = d[2:164]
        segs = [d[164 + 12 * i:176 + 12 * i] + bytes(4) for i in range(n)]
        segs += segs[:8]
        data = struct.pack('<H', n) + header + b''.join(segs)
        largest = max(largest, len(data))
        with open(os.path.join(gen, f'track{t:02X}.bin'), 'wb') as f:
            f.write(data)
    with open(os.path.join(gen, 'tracks.h'), 'w') as f:
        f.write('// Generated by tools/mkdata.py - do not edit\n#pragma once\n'
                f'#define TRACK_SIZE {largest}  // the largest course file\n')


def main():
    orig, gen = sys.argv[1], sys.argv[2]
    os.makedirs(gen, exist_ok=True)
    tables(orig, gen)
    roadpat(orig, gen)
    program_tables(orig, gen)
    tracks(orig, gen)


if __name__ == '__main__':
    main()
