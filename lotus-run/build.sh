#!/bin/sh
# Builds Lotus Run. The game's data comes from LOTUS_ZIP (by default
# lotus-data.zip in the repository's root, which git ignores):
# tools/extract.py unpacks its files into build/orig,
# tools/mkdata.py and tools/mksprites.py turn them into C data (build/gen)
# and the files of the disk (build/disk); none of it goes into the
# repository. tools/mkpages.py renders the screens around the race. Then
# everything is compiled into build/lotus-run.prg, which goes onto
# build/lotus-run.d81 together with the data files. The version is in the
# file VERSION.
# Called by .vscode/run-current.sh with the compiler in $MEGA65_CC.

set -e
cd "$(dirname "$0")"
CC=${MEGA65_CC:-../toolchain/llvm-mos/bin/mos-mega65-clang}
LOTUS_ZIP=${LOTUS_ZIP:-../lotus-data.zip}
VERSION=$(cat VERSION)

# build/gen and build/disk are made anew each time
rm -rf build/gen build/disk
mkdir -p build/gen build/disk
python3 tools/extract.py "$LOTUS_ZIP" build/orig
python3 tools/mkdata.py build/orig build/gen
python3 tools/mksprites.py build/orig build/gen
python3 tools/mkpages.py build/gen
printf '// Generated by build.sh from VERSION - do not edit\n#define VERSION "%s"\n' "$VERSION" \
    > build/gen/version.h
# The structures' offsets and the constants for the assembly, from the C
# headers on the host
${HOST_CC:-cc} -Wall -Isrc -Ibuild/gen -o build/offsets tools/offsets.c
build/offsets > build/gen/offsets.inc

# src/ref/ holds the C references of what runs in assembly: not built here
# (tests/)
# shellcheck disable=SC2086
"$CC" -Os -g -Wall $LOTUS_CFLAGS -Isrc -Ibuild/gen -o build/lotus-run.prg \
    -Wl,-Map=build/lotus-run.map src/*.c src/*.s build/gen/*.c

# The data files, each behind two bytes of (unused) load address
set --
for f in build/gen/track*.bin build/gen/roadpat.bin build/gen/spr*.bin build/gen/back*.bin build/gen/panel.bin build/gen/lapbar.bin build/gen/pages/*.bin; do
    name=$(basename "$f" .bin | tr a-z A-Z)
    { printf '\000\000'; cat "$f"; } > "build/disk/$name"
    set -- "$@" "build/disk/$name=$name"
done
../toolchain/tools/bin/mkd81.py build/lotus-run.d81 "LOTUS RUN $VERSION" \
    "build/lotus-run.prg=LOTUS RUN" "$@"
